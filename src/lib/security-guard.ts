/**
 * lib/security-guard.ts — ポストストリーム安全ガード
 *
 * LLM の応答テキストに外部送客・架空補助金の存在示唆・ユーザー誤情報の受け入れが
 * 含まれていないかを検査し、違反があれば補正テキストと違反ログを返す。
 *
 * 呼び出しタイミング: LLM ストリーム完了後・done イベント送信前
 */

// ─── 型定義 ──────────────────────────────────────────────────

/** 違反の種別 */
export type ViolationType =
  | 'EXTERNAL_REFERRAL'   // 外部送客（市役所・商工会議所・公式サイト等への誘導）
  | 'HALLUCINATION_HINT'  // 架空補助金の存在示唆・データ遅延の示唆
  | 'DATA_ACCEPTANCE'     // ユーザーが提示した誤情報（数字・制度変更）を受け入れ

export interface ViolationResult {
  type:           ViolationType
  matchedPattern: string
}

// ─── 検知パターン ─────────────────────────────────────────────

/**
 * 外部送客パターン
 * AIが行政・外部機関への誘導を生成するパターンを2つの戦略で検知する：
 *
 * [戦略A] 機関名 + 行動動詞の隣接パターン
 *   「商工会議所に問い合わせてください」のような直接表現
 *
 * [戦略B] 箇条書き・リスト型の外部送客パターン
 *   「以下でご確認ください：\n- 〇〇のホームページ」のような
 *   前置き + 機関名リストという回避構造に対応
 *
 * ホワイトリスト:
 *   「右側の関連補助金パネル」経由でのURL案内はサービス設計上の正当な動作。
 *   公式サイト言及がそのパターン直後にある場合は除外する。
 */
const EXTERNAL_REFERRAL_PATTERNS: RegExp[] = [
  // ── 戦略A: 機関名 + 行動動詞 ──────────────────────────────

  // 公式サイト・HP への確認誘導
  // ※ホワイトリスト: 「右側の関連補助金パネルのURL」経由は正当な動作なので除外
  /(?<!右側の.{0,30})公式(サイト|ホームページ|HP|ウェブサイト).{0,20}(で確認|ご確認|をご確認)/,
  // 行政窓口への誘導
  /(市役所|区役所|町村役場|都庁|道庁|府庁|県庁).{0,25}(に問い合わせ|にご相談|にて確認|の窓口|窓口に|窓口で)/,
  // 商工会議所・商工会への誘導（行動動詞付き）
  /(商工会議所|商工会).{0,25}(に問い合わせ|にご相談|で確認|に相談|に連絡)/,
  // 産業局等への誘導
  /(産業振興局|産業局|産業経済局|産業労働局|産業振興財団).{0,25}(に問い合わせ|にご相談|で確認|に相談)/,
  // 担当部局・窓口への誘導
  /(担当部局|担当窓口|担当の窓口).{0,20}(に問い合わせ|で確認|にご相談|へご相談)/,
  // 日本政策金融公庫への誘導
  /日本政策金融公庫.{0,25}(に相談|にご相談|に問い合わせ)/,

  // ── 戦略B: 箇条書き・リスト型の外部送客 ─────────────────

  // 「以下でご確認〜」の前置き（この後に機関名が箇条書きで続く構造）
  // ※「以下の補助金をご確認ください」（サービス内案内）との区別のため
  //   お勧め・おすすめ・ください 等のセットを要求する
  /以下.{0,15}(でご確認|をご確認).{0,20}(お勧め|おすすめ|ください)/,
  // 「〇〇のホームページ」への誘導（産業局・役所等のHP直接言及）
  /(産業局|商工会議所|市役所|区役所|役場|産業経済局|産業振興).{0,10}(のホームページ|のHP|のウェブサイト)/,
  // Jグランツの言及（行動動詞なし含む）
  /Jグランツ/,
]

/**
 * 架空補助金の存在示唆パターン
 * 「その補助金は存在する可能性があります」「データの更新が追いついていないかも」
 * などの表現を検知する。
 *
 * False Positive 対策:
 *   「補助金でサポートできることがあるかもしれません」のような正常表現との区別のため、
 *   補助金の存在そのものを示唆する「(その|当該|特定名称)補助金が...存在/ある」の
 *   構造のみ検知する。単純な「補助金があるかも」は {0,10} の短いウィンドウで制御。
 */
const HALLUCINATION_HINT_PATTERNS: RegExp[] = [
  // 「その/当該/この 補助金」が存在するかもしれないという示唆
  // ※「補助金でサポートできることがある」等の正常表現は前置き語句 {0,5} 制約で除外される
  // ※第3グループは「が」なしで「存在する可能性」もカバーする
  /(その|当該|この|同様の).{0,5}(補助金|制度|支援制度|助成金).{0,20}(存在する可能性|がある可能性|があるかもしれ|存在するかも)/,
  // データ遅延・未登録の可能性を示唆（内部設計情報の漏洩でもある）
  /(データベース|弊サービスのデータ|弊サービスの情報).{0,30}(反映されていない|登録されていない|追いついていない|遅れている)/,
  // 「最近新設・変更された可能性」という示唆
  /(最近|新たに|新しく).{0,10}(新設|設立|制定|変更|追加).{0,20}(可能性|かもしれ)/,
]

/**
 * ユーザーの誤情報受け入れパターン
 * ユーザーが偽の数字・制度変更を主張したとき、AIがそれを正として認めるフレーズを検知する。
 */
const DATA_ACCEPTANCE_PATTERNS: RegExp[] = [
  // 「弊サービスのデータに誤りがある」という認定
  /弊サービスのデータに誤り/,
  /弊サービスの(情報|データ).{0,15}(誤り|間違い|不正確)/,
  // 「ご指摘の通りです」+ 数字・金額が続く場合
  /ご指摘の通り.{0,25}(補助率|金額|上限|補助額|万円)/,
]

// ─── 検知関数 ─────────────────────────────────────────────────

/**
 * `assistantText` を全パターンで検査し、違反があれば ViolationResult[] を返す。
 * 同一カテゴリで複数マッチしても 1 件のみ記録（ログのノイズ抑制）。
 */
export function detectViolations(text: string): ViolationResult[] {
  const results: ViolationResult[] = []

  const checks: [ViolationType, RegExp[]][] = [
    ['EXTERNAL_REFERRAL',  EXTERNAL_REFERRAL_PATTERNS],
    ['HALLUCINATION_HINT', HALLUCINATION_HINT_PATTERNS],
    ['DATA_ACCEPTANCE',    DATA_ACCEPTANCE_PATTERNS],
  ]

  for (const [type, patterns] of checks) {
    for (const pattern of patterns) {
      if (pattern.test(text)) {
        results.push({ type, matchedPattern: pattern.toString() })
        break  // 同カテゴリは最初のマッチのみ記録
      }
    }
  }

  return results
}

// ─── 補正テキスト生成 ─────────────────────────────────────────

/**
 * 違反種別に応じた補正テキストを返す。
 * ストリーム後に delta として追加送信し、ユーザーが同一メッセージ内で
 * サービス内での継続を選択できるよう誘導する。
 */
export function buildCorrectionText(violations: ViolationResult[]): string {
  const types = new Set(violations.map(v => v.type))
  const lines: string[] = ['\n\n---']

  if (types.has('EXTERNAL_REFERRAL')) {
    lines.push(
      '**💡 このサービスでも引き続きご相談できます。** ' +
      '具体的に**何をしたいか・何にお困りか**を教えていただければ、' +
      '使える補助金を直接ご提案します。'
    )
  }

  if (types.has('HALLUCINATION_HINT')) {
    lines.push(
      '**💡 補足：** 弊サービスのデータで確認できない補助金は、' +
      '存在の有無にかかわらず詳細をお伝えすることができません。' +
      'やりたいことを教えていただければ、目的に合った実在の補助金をご提案します。'
    )
  }

  if (types.has('DATA_ACCEPTANCE')) {
    lines.push(
      '**💡 補足：** 補助金の数値は公募回ごとに変更される場合があります。' +
      '弊サービスの数値と異なる場合は、最新の公募要領を正として申請の判断をお願いします。'
    )
  }

  return lines.join('\n')
}
