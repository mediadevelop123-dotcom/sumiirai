let applied = 0, missing = 0
for (const [titleKey, pairs] of Object.entries(PATCHES)) {
  const r = rows.find(x => x.title.includes(titleKey))
  if (!r) { console.log(`⚠ エントリ未発見: ${titleKey}`); missing++; continue }
  for (const [oldT, newT] of pairs) {
    if (!r.prompt1.includes(oldT)) { console.log(`⚠ 旧テキスト不一致: [${titleKey}] "${oldT.slice(0, 24)}…"`); missing++; continue }
    r.prompt1 = r.prompt1.replace(oldT, newT)
    applied++
  }
  console.log(`✓ ${r.title}`)
}

